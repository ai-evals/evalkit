#!/usr/bin/env python3
"""Render a tap formula from digests produced by the verified release build."""
import pathlib
import sys

version, sumsfile = sys.argv[1:]
sums = {}
for line in pathlib.Path(sumsfile).read_text().splitlines():
    digest, filename = line.split(maxsplit=1)
    sums[filename.lstrip('*')] = digest

url = f"https://github.com/ai-evals/evalkit/releases/download/v{version}/"

def stanza(os, arch):
    filename = f"evalkit_v{version}_{os}_{arch}.tar.gz"
    return f'''      url "{url}{filename}"
      sha256 "{sums[filename]}"'''

print(f'''# Generated by scripts/render_formula.py after verified release publication.
class Evalkit < Formula
  desc "Go evaluation harness with typed outcomes and verifiable evidence"
  homepage "https://github.com/ai-evals/evalkit"
  version "{version}"
  license "Apache-2.0"

  on_macos do
    if Hardware::CPU.arm?
{stanza('darwin','arm64')}
    else
{stanza('darwin','amd64')}
    end
  end

  on_linux do
    if Hardware::CPU.arm?
{stanza('linux','arm64')}
    else
{stanza('linux','amd64')}
    end
  end

  def install
    bin.install "evalkit"
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/evalkit version")
  end
end''')
